import { createCanvas, GlobalFonts, loadImage } from '@napi-rs/canvas';
import { existsSync, writeFileSync } from 'fs';
import { resolve, dirname } from 'path';
import { fileURLToPath } from 'url';

// Register a system Chinese font under one alias. PingFang.ttc left
// /System/Library/Fonts on recent macOS, and a font that fails to register does
// not throw — every Chinese glyph just renders as a box. So take the first
// candidate that actually registers, and fail loudly if none does.
const CJK_FONTS = [
  '/System/Library/Fonts/PingFang.ttc',
  '/System/Library/Fonts/Hiragino Sans GB.ttc',
  '/System/Library/Fonts/STHeiti Medium.ttc',
];
const cjkFont = CJK_FONTS.find((f) => existsSync(f) && GlobalFonts.registerFromPath(f, 'OG CJK'));
if (!cjkFont) throw new Error(`no usable Chinese font, tried: ${CJK_FONTS.join(', ')}`);

const __dirname = dirname(fileURLToPath(import.meta.url));

const WIDTH = 1200;
const HEIGHT = 630;

const canvas = createCanvas(WIDTH, HEIGHT);
const ctx = canvas.getContext('2d');

// Background
ctx.fillStyle = '#050508';
ctx.fillRect(0, 0, WIDTH, HEIGHT);

// Subtle green glow line at 68% height
const glowY = HEIGHT * 0.68;
const gradient = ctx.createRadialGradient(WIDTH / 2, glowY, 0, WIDTH / 2, glowY, 300);
gradient.addColorStop(0, 'rgba(0, 255, 136, 0.08)');
gradient.addColorStop(1, 'rgba(0, 255, 136, 0)');
ctx.fillStyle = gradient;
ctx.fillRect(0, glowY - 300, WIDTH, 600);

// Thin green pulse line
ctx.strokeStyle = 'rgba(0, 255, 136, 0.3)';
ctx.lineWidth = 1.5;
ctx.beginPath();
ctx.moveTo(0, glowY);
ctx.lineTo(WIDTH, glowY);
ctx.stroke();

// Brand lockup — logo tile + wordmark, centred as one unit.
// The tile is public/kaitu-icon.png, generated by webapp/brand-assets/kaitu/generate.sh
// (run that first after a logo change).
const logo = await loadImage(resolve(__dirname, '../public/kaitu-icon.png'));
const LOGO = 84;
const LOCKUP_GAP = 22;
const lockupY = HEIGHT * 0.17;
ctx.fillStyle = '#ffffff';
ctx.font = 'bold 54px "OG CJK", sans-serif';
ctx.textAlign = 'left';
ctx.textBaseline = 'middle';
const wordmark = '开途';
const lockupWidth = LOGO + LOCKUP_GAP + ctx.measureText(wordmark).width;
const lockupX = (WIDTH - lockupWidth) / 2;
ctx.drawImage(logo, lockupX, lockupY - LOGO / 2, LOGO, LOGO);
ctx.fillText(wordmark, lockupX + LOGO + LOCKUP_GAP, lockupY + 2);

// Main title — Chinese slogan
ctx.fillStyle = '#ffffff';
ctx.font = 'bold 72px "OG CJK", sans-serif';
ctx.textAlign = 'center';
ctx.textBaseline = 'middle';
ctx.fillText('别人断线，你满速。', WIDTH / 2, HEIGHT * 0.40);

// Secondary — English slogan
ctx.fillStyle = '#00ff88';
ctx.font = 'bold 40px monospace';
ctx.fillText("Others Drop. You Don't.", WIDTH / 2, HEIGHT * 0.53);

// Tagline
ctx.fillStyle = '#9ca3af';
ctx.font = '24px "OG CJK", sans-serif';
ctx.fillText('k2cc — 越拥堵，越从容', WIDTH / 2, HEIGHT * 0.80);

// Domain
ctx.fillStyle = '#6b7280';
ctx.font = '20px monospace';
ctx.fillText('kaitu.io', WIDTH / 2, HEIGHT * 0.90);

// Save
const buffer = canvas.toBuffer('image/png');
const outputPath = resolve(__dirname, '../public/images/og-default.png');
writeFileSync(outputPath, buffer);
console.log(`OG image generated: ${outputPath} (${buffer.length} bytes)`);
