package main

import (
	"flag"
	"fmt"
	"io"
	"os"
	"path/filepath"
	"runtime"
	"strings"

	"github.com/kaitu-io/k2/config"
)

// cmdSetup generates a client config (or copies an existing one), installs the
// system service, and starts it.
//
// Usage:
//
//	k2 setup <URL>           — generate config with server URL + install
//	k2 setup -c config.yaml — copy config to target dir + install
func cmdSetup(args []string) {
	fs := flag.NewFlagSet("setup", flag.ExitOnError)
	srcConfig := fs.String("c", "", "existing config file to install")
	fs.Usage = func() {
		fmt.Fprintf(os.Stderr, "Usage: k2 setup [URL]\n")
		fmt.Fprintf(os.Stderr, "       k2 setup -c config.yaml\n\n")
		fs.PrintDefaults()
	}
	fs.Parse(args)

	// Determine target config path.
	targetDir := setupConfigDir()
	targetPath := filepath.Join(targetDir, "k2.yaml")

	switch {
	case *srcConfig != "":
		// Copy the provided config to the target location.
		if err := copyConfig(*srcConfig, targetPath); err != nil {
			fmt.Fprintf(os.Stderr, "Error: copy config: %v\n", err)
			os.Exit(1)
		}
		fmt.Printf("Config installed to %s\n", targetPath)

	case fs.NArg() > 0:
		// Generate config from URL.
		wireURL := fs.Arg(0)
		if !strings.Contains(wireURL, "://") {
			fmt.Fprintf(os.Stderr, "Error: expected a k2v5:// or k2subs:// URL, got %q\n", wireURL)
			os.Exit(1)
		}
		var cfg *config.ClientConfig
		if strings.HasPrefix(wireURL, "k2subs://") {
			cfg = config.ClientFromSubsURL(wireURL)
		} else {
			cfg = config.ClientFromURL(wireURL)
		}
		if err := writeConfigFile(cfg, targetPath, os.Stderr); err != nil {
			fmt.Fprintf(os.Stderr, "Error: write config: %v\n", err)
			os.Exit(1)
		}
		fmt.Printf("Config generated at %s\n", targetPath)

	default:
		fmt.Fprintf(os.Stderr, "Error: provide a URL or use -c config.yaml\n\n")
		fs.Usage()
		os.Exit(1)
	}

	// Validate the installed config.
	cfg, err := config.LoadClient(targetPath)
	if err != nil {
		fmt.Fprintf(os.Stderr, "Error: load config: %v\n", err)
		os.Exit(1)
	}
	if err := config.ValidateClient(cfg); err != nil {
		fmt.Fprintf(os.Stderr, "Error: invalid config: %v\n", err)
		os.Exit(1)
	}

	// Install and start the system service.
	fmt.Println("Installing service...")
	if err := installService(); err != nil {
		fmt.Fprintf(os.Stderr, "Error: install service: %v\n", err)
		os.Exit(1)
	}

	fmt.Println("Service installed and started.")
	fmt.Println()
	fmt.Println("Next steps:")
	fmt.Printf("  Check status:     k2 status\n")
	fmt.Printf("  Connect:          k2 up\n")
	fmt.Printf("  Disconnect:       k2 down\n")
	fmt.Printf("  Remove service:   k2 service uninstall\n")
}

// setupConfigDir returns the directory where k2 setup writes the config file.
// Uses system-wide dir when running as root; user dir otherwise.
func setupConfigDir() string {
	if config.IsRoot() {
		if runtime.GOOS == "windows" {
			if pd := os.Getenv("ProgramData"); pd != "" {
				return filepath.Join(pd, "k2")
			}
		}
		return "/etc/k2"
	}
	// User dir: ~/.config/k2/
	if home, err := os.UserHomeDir(); err == nil {
		return filepath.Join(home, ".config", "k2")
	}
	return os.TempDir()
}

// copyConfig copies the config file at src to dst, creating parent directories.
func copyConfig(src, dst string) error {
	data, err := os.ReadFile(src)
	if err != nil {
		return fmt.Errorf("read %s: %w", src, err)
	}
	if err := os.MkdirAll(filepath.Dir(dst), 0755); err != nil {
		return fmt.Errorf("create dir: %w", err)
	}
	return os.WriteFile(dst, data, 0644)
}

// writeConfigFile writes a ClientConfig as YAML to dst, creating parent dirs.
// Uses a simple YAML template rather than a full marshal to keep output readable.
func writeConfigFile(cfg *config.ClientConfig, dst string, stderr io.Writer) error {
	if err := os.MkdirAll(filepath.Dir(dst), 0755); err != nil {
		return fmt.Errorf("create dir: %w", err)
	}

	// Use the first route's via URL (works for both k2v5 and k2subs).
	via := ""
	if len(cfg.Routes) > 0 {
		via = cfg.Routes[0].Via
	}
	if via == "" {
		via = cfg.Server
	}

	content := fmt.Sprintf(`# k2 client configuration — generated by k2 setup
routes:
  - via: %q
    match:
      all: true
mode: %s
`, via, cfg.Mode)

	return os.WriteFile(dst, []byte(content), 0644)
}
